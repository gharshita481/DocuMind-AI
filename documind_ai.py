def is_useful_chunk(text):
    cleaned = text.strip()
    lower = cleaned.lower()

    # Skip very short passages
    if len(cleaned) < 150:
        return False

    # Skip chunks that appear to be bibliography sections
    reference_markers = [
        "references\n",
        "bibliography\n",
        "works cited\n"
    ]

    if any(marker in lower for marker in reference_markers):
        return False

    return True


