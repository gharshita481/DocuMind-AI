def delete_document(name):
    if not name:
        return (
            "Please select a PDF to delete.",
            gr.update(choices=get_documents(), value=None)
        )

    before = len(doc_store["chunks"])

    doc_store["chunks"] = [
        c for c in doc_store["chunks"]
        if str(chunk_value(
            c,
            ["source", "filename", "file_name", "document"],
            "Unknown PDF"
        )) != str(name)
    ]

    removed = before - len(doc_store["chunks"])

    rebuild_search_index(doc_store["chunks"])

    status = (
        f"Deleted **{name}** successfully.\n\n"
        f"Removed chunks: {removed}"
    )

    return status, gr.update(choices=get_documents(), value=None)


