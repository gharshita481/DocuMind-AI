def analytics_report():

    chunks = doc_store["chunks"]

    if not chunks:
        return "No documents indexed yet."

    documents = get_documents()

    all_text = " ".join([
        str(chunk_value(c, ["text", "content"], ""))
        for c in chunks
    ])

    words = re.findall(r"\b[a-zA-Z]{3,}\b", all_text.lower())

    stop_words = {
        "the", "and", "for", "with", "this", "that",
        "from", "are", "was", "were", "have", "has",
        "into", "their", "they", "which", "using",
        "can", "will", "not", "also", "been", "its",
        "our", "but", "such", "than", "then"
    }

    filtered_words = [
        w for w in words if w not in stop_words
    ]

    top_words = Counter(filtered_words).most_common(15)

    page_count = len(set(
        (
            str(chunk_value(c, ["source", "filename"], "Unknown")),
            str(chunk_value(c, ["page", "page_number"], "?"))
        )
        for c in chunks
    ))

    report = "# Document Analytics Report\n\n"

    report += f"**Total Documents:** {len(documents)}\n\n"
    report += f"**Indexed Pages:** {page_count}\n\n"
    report += f"**Total Chunks:** {len(chunks)}\n\n"
    report += f"**Words in Indexed Chunks:** {len(words)}\n\n"

    report += "## Top Research Keywords\n\n"

    for word, count in top_words:
        report += f"- **{word}** — {count} occurrences\n"

    report += "\n## Uploaded Documents\n\n"

    for name in documents:
        report += f"- {name}\n"

    return report


