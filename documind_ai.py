# Common words excluded from keyword analysis
STOP_WORDS = {
    "the", "is", "are", "was", "were", "a", "an", "and",
    "or", "of", "to", "in", "on", "for", "with", "by",
    "this", "that", "these", "those", "it", "its", "as",
    "at", "be", "been", "from", "we", "our", "their",
    "they", "he", "she", "which", "who", "what", "how",
    "can", "could", "may", "might", "will", "would",
    "using", "used", "use", "also", "such", "than",
    "into", "between", "within", "through", "based"
}


def get_document_analytics():

    chunks = doc_store["chunks"]

    if not chunks:
        return {
            "documents": 0,
            "chunks": 0,
            "pages": 0,
            "words": 0,
            "keywords": [],
            "document_list": []
        }

    sources = sorted(set(
        chunk["source"] for chunk in chunks
    ))

    pages = set(
        (chunk["source"], chunk["page"])
        for chunk in chunks
    )

    all_text = " ".join(
        chunk["text"] for chunk in chunks
    )

    words = re.findall(
        r"\b[a-zA-Z]{3,}\b",
        all_text.lower()
    )

    keywords = Counter(
        word for word in words
        if word not in STOP_WORDS
    )

    document_list = []

    for source in sources:

        source_chunks = [
            chunk for chunk in chunks
            if chunk["source"] == source
        ]

        source_pages = len(set(
            chunk["page"] for chunk in source_chunks
        ))

        document_list.append({
            "filename": source,
            "indexed_pages": source_pages,
            "chunks": len(source_chunks)
        })

    return {
        "documents": len(sources),
        "chunks": len(chunks),
        "pages": len(pages),
        "words": len(words),
        "keywords": keywords.most_common(10),
        "document_list": document_list
    }


def get_analytics_report():

    data = get_document_analytics()

    if data["documents"] == 0:
        return "No documents have been processed yet."

    report = f"""
## Document Analytics

- **Total Documents:** {data['documents']}
- **Indexed Pages:** {data['pages']}
- **Total Chunks:** {data['chunks']}
- **Extracted Words:** {data['words']}

### Top Keywords

"""

    for word, count in data["keywords"]:
        report += f"- **{word}** — {count} occurrences\n"

    report += "\n### Document Details\n"

    for doc in data["document_list"]:
        report += (
            f"- **{doc['filename']}** | "
            f"{doc['indexed_pages']} indexed pages | "
            f"{doc['chunks']} chunks\n"
        )

    return report


