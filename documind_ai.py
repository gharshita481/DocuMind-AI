def retrieve_context(
    question,
    scope="All Documents",
    top_k=5
):

    if index is None or not chunks:
        return []

    query_embedding = embedding_model.encode(
        [question],
        convert_to_numpy=True
    )

    query_embedding = np.asarray(
        query_embedding,
        dtype=np.float32
    )

    faiss_index = __import__("faiss")

    faiss_index.normalize_L2(
        query_embedding
    )

    scores, indices = index.search(
        query_embedding,
        min(top_k, len(chunks))
    )

    results = []

    for score, idx in zip(
        scores[0],
        indices[0]
    ):

        if idx < 0:
            continue

        metadata = chunk_metadata[idx]

        if (
            scope != "All Documents"
            and metadata["document"] != scope
        ):
            continue

        results.append({
            "text": chunks[idx],
            "document": metadata["document"],
            "page": metadata["page"],
            "score": float(score)
        })

    return results


