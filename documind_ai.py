def split_text(text, chunk_size=700, overlap=120):

    words = text.split()

    result = []

    start = 0

    while start < len(words):

        end = start + chunk_size

        piece = " ".join(words[start:end])

        if piece.strip():
            result.append(piece)

        start += chunk_size - overlap

    return result


