import re

def conversational_qa(message, history=None):

    if not message or not message.strip():
        return "Please enter a question."

    history = history or []

    # Find the most recent user question
    previous_question = None

    for item in reversed(history):

        if isinstance(item, dict):

            if item.get("role") == "user":
                previous_question = item.get("content")
                break

        elif isinstance(item, (list, tuple)) and len(item) >= 1:
            # Compatibility with older Gradio history format
            previous_question = item[0]
            if previous_question:
                break

    current_question = message.strip()

    # Detect short or context-dependent follow-up questions
    followup_pattern = (
        r"\b(it|its|they|them|this|that|these|those|"
        r"their|above|same|also|more|explain further|"
        r"what about|how about|why|elaborate)\b"
    )

    is_followup = (
        len(current_question.split()) <= 8
        or re.search(followup_pattern, current_question.lower())
    )

    if previous_question and is_followup:

        resolved_question = (
            f"Previous user question: {previous_question}\n"
            f"Current follow-up question: {current_question}\n"
            "Answer the current follow-up question using the "
            "previous question only as context."
        )

    else:
        resolved_question = current_question

    # Use the existing document Q&A engine
    return universal_qa(resolved_question)


