def chunk_value(chunk, keys, default=""):
    for key in keys:
        if isinstance(chunk, dict) and key in chunk:
            return chunk[key]
    return default


def get_documents():
    names = set()

    for chunk in doc_store["chunks"]:
        name = chunk_value(
            chunk,
            ["source", "filename", "file_name", "document"],
            "Unknown PDF"
        )
        names.add(str(name))

    return sorted(names)


def rebuild_search_index(chunks):
    if not chunks:
        doc_store["index"] = None
        return

    texts = [
        str(chunk_value(c, ["text", "content"], ""))
        for c in chunks
    ]

    embeddings = embedding_model.encode(
        texts,
        convert_to_numpy=True,
        show_progress_bar=False
    )

    embeddings = np.asarray(embeddings, dtype="float32")
    faiss.normalize_L2(embeddings)

    index = faiss.IndexFlatIP(embeddings.shape[1])
    index.add(embeddings)

    doc_store["index"] = index


def refresh_document_choices():
    return gr.update(choices=get_documents(), value=None)


