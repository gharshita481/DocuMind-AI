# 6. DOCUMENT QUESTION ANSWERING ENGINE
# ------------------------------------------------------------

def answer_from_documents(question, selected_docs=None, history=None):

    question = str(question).strip()

    if not question:
        return "Please enter a question."

    chunks = doc_store["chunks"]

    if selected_docs:
        selected_docs = [str(x) for x in selected_docs]

        chunks = [
            c for c in chunks
            if str(chunk_value(
                c,
                ["source", "filename", "file_name", "document"],
                "Unknown PDF"
            )) in selected_docs
        ]

    if not chunks:
        return "No indexed PDF content is available for the selected documents."

    # Retrieve relevant chunks
    query_embedding = embedding_model.encode(
        [question],
        convert_to_numpy=True
    )

    query_embedding = np.asarray(
        query_embedding,
        dtype="float32"
    )

    faiss.normalize_L2(query_embedding)

    chunk_texts = [
        str(chunk_value(c, ["text", "content"], ""))
        for c in chunks
    ]

    document_embeddings = embedding_model.encode(
        chunk_texts,
        convert_to_numpy=True,
        show_progress_bar=False
    )

    document_embeddings = np.asarray(
        document_embeddings,
        dtype="float32"
    )

    faiss.normalize_L2(document_embeddings)

    similarities = np.dot(
        document_embeddings,
        query_embedding[0]
    )

    top_indices = np.argsort(similarities)[::-1][:6]

    relevant_chunks = [
        chunks[i]
        for i in top_indices
        if similarities[i] > 0.05
    ]

    if not relevant_chunks:
        return (
            "I could not find sufficiently relevant information "
            "in the uploaded research papers."
        )

    context_parts = []
    sources = []

    for c in relevant_chunks:
        source = str(chunk_value(
            c,
            ["source", "filename", "file_name", "document"],
            "Unknown PDF"
        ))

        page = chunk_value(c, ["page", "page_number"], "?")
        text_part = str(chunk_value(c, ["text", "content"], ""))

        context_parts.append(
            f"Source: {source}, Page: {page}\n{text_part}"
        )

        sources.append(f"{source} (Page {page})")

    context = "\n\n".join(context_parts)
    context = context[:3500]

    prompt = f"""
You are DocuMind AI, an academic research paper assistant.

Answer the user's question using the research paper content below.

Instructions:
1. Give a meaningful and explanatory answer.
2. Use simple, clear academic English.
3. Explain the important points in a connected paragraph.
4. Avoid one-word or extremely short answers.
5. Use bullet points only when they improve clarity.
6. Do not invent facts that are not present in the papers.
7. If the information is not available, clearly say so.
8. Focus on the exact question asked.

Research paper content:
{context}

Question:
{question}

Detailed answer:
"""

    try:
        inputs = tokenizer(
            prompt,
            return_tensors="pt",
            truncation=True,
            max_length=512
        )

        device = next(model.parameters()).device

        inputs = {
            k: v.to(device)
            for k, v in inputs.items()
        }

        outputs = model.generate(
            **inputs,
            max_new_tokens=220,
            num_beams=4,
            early_stopping=True
        )

        answer = tokenizer.decode(
            outputs[0],
            skip_special_tokens=True
        ).strip()

    except Exception as e:
        return "AI generation error: " + str(e)

    if len(answer.split()) < 12:
        answer += (
            "\n\nThe retrieved paper content contains limited "
            "information about this question."
        )

    unique_sources = list(dict.fromkeys(sources))

    answer += "\n\n---\n**Sources consulted:**\n"
    answer += "\n".join("- " + s for s in unique_sources)

    return answer


