# 10. AI ANSWER GENERATION
# ============================================================

def generate_answer(
    question,
    scope="All Documents"
):

    if not documents:

        return (
            "Please upload a research paper first.",
            ""
        )

    retrieved = retrieve_context(
        question,
        scope,
        top_k=5
    )

    if not retrieved:

        return (
            "No relevant information was found "
            "in the selected research papers.",
            ""
        )

    context = "\n\n".join(
        item["text"]
        for item in retrieved
    )

    prompt = f"""
You are DocuMind AI, a research paper assistant.

Answer the question using only the context below.

Instructions:
1. Give a clear and detailed answer.
2. Use simple academic English.
3. Explain important concepts properly.
4. Do not invent information.
5. If the answer is unavailable, clearly mention it.

Research Context:
{context}

Question:
{question}

Answer:
"""

    inputs = tokenizer(
        prompt,
        return_tensors="pt",
        max_length=512,
        truncation=True
    )

    device = next(model.parameters()).device

    inputs = {
        key: value.to(device)
        for key, value in inputs.items()
    }

    with torch.no_grad():

        outputs = model.generate(
            **inputs,
            max_new_tokens=220,
            num_beams=4,
            early_stopping=True
        )

    answer = tokenizer.decode(
        outputs[0],
        skip_special_tokens=True
    )

    sources = "\n".join(
        [
            f"- {item['document']} — Page {item['page']}"
            for item in retrieved
        ]
    )

    return answer, sources


