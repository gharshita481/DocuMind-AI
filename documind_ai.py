def keyword_analysis():

    if not documents:
        return None

    all_text = " ".join(
        page["text"]
        for pages in documents.values()
        for page in pages
    )

    words = re.findall(
        r"\b[a-zA-Z]{4,}\b",
        all_text.lower()
    )

    stopwords = {
        "this", "that", "with", "from",
        "have", "were", "which", "their",
        "there", "these", "those", "been",
        "also", "into", "using", "used"
    }

    counts = Counter(
        word
        for word in words
        if word not in stopwords
    )

    top = counts.most_common(10)

    if not top:
        return None

    labels = [
        item[0] for item in top
    ]

    values = [
        item[1] for item in top
    ]

    fig, ax = plt.subplots(figsize=(9, 4))

    ax.barh(
        labels[::-1],
        values[::-1]
    )

    ax.set_title(
        "Top Research Keywords"
    )

    ax.set_xlabel("Frequency")

    plt.tight_layout()

    return fig


