def send_chat(message, history, selected_docs, cid):

    if not message or not str(message).strip():
        return "", history or [], cid, gr.update(
            choices=get_saved_chats()
        )

    if cid is None:
        cid = create_chat()

    history = history or []

    save_chat_message(cid, "user", message)

    answer = answer_from_documents(
        message,
        selected_docs,
        history
    )

    save_chat_message(cid, "assistant", answer)

    updated_history = history + [
        {"role": "user", "content": message},
        {"role": "assistant", "content": answer}
    ]

    return (
        "",
        updated_history,
        cid,
        gr.update(choices=get_saved_chats(), value=str(cid))
    )


def new_chat():
    cid = create_chat()

    return (
        cid,
        [],
        gr.update(choices=get_saved_chats(), value=str(cid))
    )


def open_chat(cid):
    if not cid:
        return [], None

    messages = load_chat_messages(cid)

    return messages, int(cid)


def remove_chat(cid):
    if not cid:
        return [], None, gr.update(choices=get_saved_chats())

    conn = sqlite3.connect(DB_PATH)
    cur = conn.cursor()

    cur.execute(
        "DELETE FROM messages WHERE conversation_id = ?",
        (int(cid),)
    )

    cur.execute(
        "DELETE FROM conversations WHERE id = ?",
        (int(cid),)
    )

    conn.commit()
    conn.close()

    return (
        [],
        None,
        gr.update(choices=get_saved_chats(), value=None)
    )


