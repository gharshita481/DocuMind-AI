# 4. MULTIPLE PDF UPLOAD
# ------------------------------------------------------------

def upload_documents(files):
    if not files:
        return "Please select at least one PDF.", gr.update(
            choices=get_documents()
        )

    existing = set(get_documents())
    added = []
    skipped = []
    new_chunks = []

    for file_path in files:
        if not file_path or not os.path.exists(file_path):
            continue

        filename = os.path.basename(file_path)

        if filename in existing:
            skipped.append(filename)
            continue

        try:
            pdf = fitz.open(file_path)

            for page_number, page in enumerate(pdf, start=1):
                page_text = page.get_text("text").strip()

                if not page_text:
                    continue

                # Split page text into overlapping chunks
                chunk_size = 1200
                overlap = 200
                start = 0

                while start < len(page_text):
                    end = start + chunk_size
                    text_part = page_text[start:end].strip()

                    if text_part:
                        new_chunks.append({
                            "text": text_part,
                            "source": filename,
                            "page": page_number
                        })

                    start += chunk_size - overlap

            pdf.close()
            added.append(filename)
            existing.add(filename)

        except Exception as e:
            skipped.append(filename + " (Error: " + str(e) + ")")

    if new_chunks:
        doc_store["chunks"].extend(new_chunks)
        rebuild_search_index(doc_store["chunks"])

    status = "## PDF Processing Report\n\n"

    status += "**Successfully added:** " + str(len(added)) + "\n\n"

    if added:
        status += "\n".join("- " + x for x in added) + "\n\n"

    status += "**Skipped / already uploaded / errors:** " + str(len(skipped))

    if skipped:
        status += "\n\n" + "\n".join("- " + x for x in skipped)

    status += "\n\n**Total indexed chunks:** " + str(
        len(doc_store["chunks"])
    )

    return status, gr.update(choices=get_documents())


