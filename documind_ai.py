def universal_qa(question, history=None):
    if not question or not question.strip():
        return "Please enter a question."

    chunks = doc_store["chunks"]
    index = doc_store["index"]

    if index is None or not chunks:
        return "Please upload and process a PDF first."

    q = question.strip()
    q_lower = q.lower()

    # Detect requests targeting particular PDF pages/slides
    page_numbers = None

    if re.search(r"\b(first|1st)\s+(two|2|2nd)\s+(slides?|pages?)\b", q_lower):
        page_numbers = {1, 2}
    else:
        match = re.search(
            r"\bpage\s+(\d+)(?:\s*(?:-|to|and)\s*(\d+))?\b",
            q_lower
        )
        if match:
            start_page = int(match.group(1))
            end_page = int(match.group(2) or start_page)
            if end_page >= start_page and end_page - start_page < 10:
                page_numbers = set(range(start_page, end_page + 1))

    # Directly select requested pages when available
    if page_numbers:
        retrieved = [
            {
                **chunk,
                "score": 1.0
            }
            for chunk in chunks
            if chunk["page"] in page_numbers
        ]

        if not retrieved:
            page_text = (
                "The requested page(s) were not found in the "
                "indexed text. Check whether the PDF's first slides "
                "are stored under different page numbers or require OCR."
            )
            return page_text

    else:
        # Semantic retrieval for general questions
        query_vector = embedding_model.encode(
            [q],
            convert_to_numpy=True,
            normalize_embeddings=True
        ).astype(np.float32)

        k = min(6, len(chunks))
        scores, ids = index.search(query_vector, k)

        retrieved = []
        for score, idx in zip(scores[0], ids[0]):
            if idx >= 0:
                retrieved.append({
                    **chunks[int(idx)],
                    "score": float(score)
                })

    # Limit context to keep it inside the generator's input budget
    context_parts = []
    budget = 1700

    for item in retrieved:
        passage = (
            f"[PDF: {item['source']}, page {item['page']}]\n"
            f"{item['text'].strip()}"
        )

        if budget <= 0:
            break

        passage = passage[:budget]
        context_parts.append(passage)
        budget -= len(passage)

    context = "\n\n".join(context_parts)

    # Put the question first so truncation is less likely to remove it
    prompt = (
        f"Question: {q}\n"
        "Answer using only the evidence in the context. "
        "Explain clearly and include examples if requested. "
        "If evidence is insufficient, say so.\n"
        f"Context:\n{context}\n"
        "Answer:"
    )

    inputs = tokenizer(
        prompt,
        return_tensors="pt",
        truncation=True,
        max_length=512
    ).to(next(model.parameters()).device)

    with torch.no_grad():
        output = model.generate(
            **inputs,
            max_new_tokens=180,
            num_beams=4,
            early_stopping=True
        )

    answer = tokenizer.decode(
        output[0],
        skip_special_tokens=True
    ).strip()

    sources = []
    seen_sources = set()

    for item in retrieved:
        key = (item["source"], item["page"])
        if key not in seen_sources:
            seen_sources.add(key)
            sources.append(
                f"- {item['source']}, page {item['page']}"
            )

    return (
        f"{answer or 'The model could not generate an answer.'}"
        "\n\n### Sources\n" + "\n".join(sources)
    )

