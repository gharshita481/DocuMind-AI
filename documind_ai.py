def generate_insights(scope):

    selected_docs = documents

    if scope != "All Documents":

        selected_docs = {
            scope: documents.get(scope, [])
        }

    if not selected_docs:

        return "Please upload a research paper first."

    all_text = []

    total_pages = 0

    for filename, pages in selected_docs.items():

        total_pages += len(pages)

        for page in pages:

            all_text.append(
                page["text"]
            )

    combined_text = " ".join(all_text)

    words = re.findall(
        r"\b[a-zA-Z]{3,}\b",
        combined_text.lower()
    )

    stopwords = {
        "the", "and", "for", "are", "was",
        "with", "that", "this", "from", "have",
        "has", "were", "been", "their", "they",
        "which", "will", "would", "could", "should",
        "into", "also", "than", "then", "when",
        "where", "what", "how", "can", "may",
        "not", "but", "all", "any", "its",
        "our", "out", "use", "used", "using"
    }

    filtered_words = [
        word for word in words
        if word not in stopwords
    ]

    counts = Counter(filtered_words)

    top_keywords = counts.most_common(15)

    output = "## Research Insights\n\n"

    output += (
        f"**Documents Analysed:** "
        f"{len(selected_docs)}\n\n"
    )

    output += (
        f"**Total Pages:** {total_pages}\n\n"
    )

    output += (
        f"**Total Words:** {len(words)}\n\n"
    )

    output += (
        f"**Unique Keywords:** {len(counts)}\n\n"
    )

    output += "### Top Research Keywords\n\n"

    for word, count in top_keywords:

        output += (
            f"- **{word}** — "
            f"{count} occurrences\n"
        )

    return output


